import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const step=Number(process.argv[2]);
if(!Number.isInteger(step)||step<1)throw Error('Provide an existing snapshot step');
const root='C:/Users/Administrator/Desktop/GS-SLAM-Lab/outputs/mini-splatting2-mip-depth-001';
const run='body-gaussian-upstream-offset';
const dir=root+'/shuolee/current/local-clothed-surface-123/demo-vhap-initialization/'+run+'/delivery/step-'+String(step).padStart(6,'0');
const m=await import(pathToFileURL(root+'/viewer/scene-package.js'));
const f=await import(pathToFileURL(root+'/viewer/camera-formats.js'));
const bytes=await fs.readFile(dir+'/point_cloud.ply'), cameraBytes=await fs.readFile(dir+'/cameras.json');
const cameras=JSON.parse(cameraBytes), context=JSON.parse(await fs.readFile(dir+'/context.json','utf8'));
const validation=JSON.parse(await fs.readFile(dir+'/validation.json','utf8'));
if(validation.format_passed!==true||validation.native_rotated_render_parity?.passed!==true||validation.native_source_ply_parity?.passed!==true)throw Error('Native export replay must pass');
if(validation.sha256!==await m.sha256(bytes))throw Error('Validated PLY SHA mismatch');
if(validation.native_replay_uses_serialized_camera!==true||validation.serialized_camera_sha256!==await m.sha256(cameraBytes))throw Error('Camera replay/SHA mismatch');
const p=await m.scenePackage(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),'ply',cameras,context);
const files=Object.fromEntries((await m.unpackSceneZip(p.bytes)).map(x=>[x.name,x.data]));
files['README.txt']=new TextDecoder().decode(files['README.txt'])+`\n全身阶段结果：${step}步，${validation.points}个高斯，SMPL-X绑定、共享vertexoffset。标准PLY固定第33帧姿态，仅配该帧相机；59帧训练包含逐帧姿态，不能把它们当作同一静态点云的59个实拍相机。手臂、背面和部分脚部仍有缺损，质量未验收。训练checkpoint及绑定信息留在工程中，PLY本身不含可驱动骨架。\n`;
files['validation.json']=await fs.readFile(dir+'/validation.json');
const zip=f.storedZip(files), entries=await m.unpackSceneZip(zip);
const checkFiles=entries.map(x=>{const file=new File([x.data],path.basename(x.name));file.sceneRelativePath=x.name;return file;});
const models=await m.primaryModelFiles(checkFiles);
if(models.length!==1)throw Error('Expected one primary model');
const paired=await m.pairedCameras(models[0],checkFiles,models);
if(paired.cameras.length!==1||!paired.verifiedBinding||paired.referenceFrameId!==validation.reference_frame)throw Error('Camera/reference mismatch');
const out='D:/00/工作/查看器/exports/demo_body_smplx_offset_'+String(step).padStart(6,'0')+'_with_camera.zip';
await fs.mkdir(path.dirname(out),{recursive:true}); await fs.writeFile(out,zip,{flag:'wx'});
const receipt={updated:new Date().toISOString(),run,step,points:validation.points,path:out,zip_sha256:await m.sha256(zip),bytes:zip.length,
  entries:entries.map(x=>x.name),cameraCount:paired.cameras.length,verifiedBinding:paired.verifiedBinding,referenceFrameId:paired.referenceFrameId,quality_accepted:false};
await fs.writeFile(dir+'/package-receipt.json',JSON.stringify(receipt,null,2),{flag:'wx'});
console.log(JSON.stringify(receipt,null,2));
