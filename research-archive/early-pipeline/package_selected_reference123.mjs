import fs from 'node:fs/promises';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
const t='C:/Users/Administrator/Desktop/GS-SLAM-Lab/outputs/mini-splatting2-mip-depth-001';
const args=process.argv.slice(2), receiptIndex=args.indexOf('--receipt');
const d=receiptIndex>=0?path.dirname(path.resolve(args[receiptIndex+1])):t+'/shuolee/current/local-clothed-surface-123/smplifyx-reference-control/official-first-cycle/limb-and-reference-review/selected-reference';
const receipt=JSON.parse(await fs.readFile(d+'/staged-delivery.json','utf8'));
const context=JSON.parse(await fs.readFile(receipt.context,'utf8'));
const {scenePackage,unpackSceneZip,sha256}=await import(pathToFileURL(t+'/viewer/scene-package.js'));
const {normalizeCameras}=await import(pathToFileURL(t+'/viewer/camera-io.js'));
const data=await fs.readFile(receipt.ply),bytes=data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength);
const cameras=normalizeCameras(context.cameras).cameras;
const packed=await scenePackage(bytes,'ply',cameras,{...context,model:{sha256:receipt.source_sha256}});
const files=await unpackSceneZip(packed.bytes.buffer.slice(packed.bytes.byteOffset,packed.bytes.byteOffset+packed.bytes.byteLength));
const scene=JSON.parse(new TextDecoder().decode(files.find(f=>f.name==='scene.json').data));
const provenance=JSON.parse(new TextDecoder().decode(files.find(f=>f.name==='camera_provenance.json').data));
if(scene.referenceFrameId!=='frame_000051'||scene.initialView!==50||packed.cameraCount!==94)throw Error('Reference identity mismatch');
if(provenance.selected!==scene.initialView)throw Error('Default camera differs between scene and provenance');
for(const root of [t+'/viewer','D:/00/工作/查看器'])await fs.writeFile(path.join(root,'models',receipt.modelId,'scene.zip'),packed.bytes);
const result={model_sha256:packed.hash,zip_sha256:await sha256(packed.bytes),cameras:packed.cameraCount,reference:scene.referenceFrameId,initialView:scene.initialView,provenanceSelected:provenance.selected,files:files.length};
await fs.writeFile(d+'/package-check.json',JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
